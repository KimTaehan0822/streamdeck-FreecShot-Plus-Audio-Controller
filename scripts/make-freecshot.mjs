// Builds com.haeunga0822.freecshot-audio.sdPlugin from the OBS plugin folder: same actions and settings screen,
// its own UUIDs and name. Only imgs/ is kept in git there; everything this script writes is generated.
import { cpSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'

const OBS = 'com.haeunga0822.obs-audio.sdPlugin'
const FC = 'com.haeunga0822.freecshot-audio.sdPlugin'
const NAME = 'Web-Socket Audio Controller for FreecShot Plus'

const manifest = JSON.parse(readFileSync(`${OBS}/manifest.json`, 'utf8').replaceAll('com.haeunga0822.obs-audio', 'com.haeunga0822.freecshot-audio'))
manifest.Name = NAME
manifest.Category = NAME
manifest.Description =
	'FreecShot Plus audio mixer meters, volume, mute, push to talk, monitoring and balance over its built-in WebSocket. Unofficial; not affiliated with SOOP.'
for (const a of manifest.Actions) if (a.Tooltip) a.Tooltip = a.Tooltip.replaceAll('OBS', 'FreecShot Plus')

mkdirSync(`${FC}/ui`, { recursive: true })
writeFileSync(`${FC}/manifest.json`, JSON.stringify(manifest, null, '\t') + '\n')
cpSync(`${OBS}/ui`, `${FC}/ui`, { recursive: true, filter: (src) => !src.endsWith('flavour.js') })
writeFileSync(`${FC}/ui/flavour.js`, "// Generated by scripts/make-freecshot.mjs.\nwindow.PI_FLAVOUR = 'freecshot'\n")
cpSync(`${OBS}/layouts`, `${FC}/layouts`, { recursive: true })
for (const f of ['THIRD-PARTY-NOTICES.txt', '.sdignore']) cpSync(`${OBS}/${f}`, `${FC}/${f}`)
